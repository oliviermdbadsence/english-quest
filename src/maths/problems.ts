export function problemById(id: string): Problem | undefined {
  for (const world of MATHS_WORLDS) {
    const found = world.problems.find((item) => item.id === id);
    if (found) return found;
  }
  return undefined;
}

export function worldOfProblem(id: string): number {
  return MATHS_WORLDS.findIndex((world) => world.problems.some((item) => item.id === id));
}
